CREATE TABLE IF NOT EXISTS tenant_notes (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 tenant_id BIGINT UNSIGNED NOT NULL, title VARCHAR(160) NOT NULL,
 content TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_tn_tenant FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
 INDEX idx_tn_tenant_id (tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
